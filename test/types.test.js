test("use type imports types for the declarations and emits no JavaScript", () => {
  const { code, declarations: types } = compile([
    'use type Datum, DatumTag from "../types"',
    'use type StreakRun from "./streaks.prose"',
    "export function first takes datum as Datum, giving DatumTag or unset", "    return datum:tags.1"
  ].join("\n"));
  assert.doesNotMatch(code, /from "\.\.\/types"|streaks/);
  assert.deepEqual(types.split("\n").slice(1, 3), [
    'import type { Datum, DatumTag } from "../types";',
    'import type { StreakRun } from "./streaks.prose";'
  ]);
});

test("annotations change nothing in the JavaScript, and modules without exports have no declarations", () => {
  const typed = compile("export function twice takes n as number, giving number\n    return n * 2").code;
  const untyped = compile("export function twice takes n\n    return n * 2").code;
  assert.equal(typed, untyped);
  assert.equal(compile("print 1").declarations, null);
  assert.deepEqual(run([
    "double is function takes n as number giving number return n * 2", "print double with 4",
    "total as number is 5", "print total",
    'type is "an ordinary variable named type"', "print type",
    "type Kind is \"a\" or \"b\"", "print type"
  ].join("\n")), [8, 5, "an ordinary variable named type", "an ordinary variable named type"]);
});

test("functions imported from typed Prose files keep their argument counts", () => {
  const files = { "./text.prose": "export function pluralize takes count as number, singular as text, plural as maybe text, giving text\n    return singular\nexport limit as number is 3" };
  const { code } = compile('use pluralize, limit from "./text.prose"\nprint pluralize 2, "tag", "tags"\nprint limit', { readModule: path => files[path] });
  assert.match(code, /_prose_pluralize\(2, "tag", "tags"\)/);
});

test("type syntax errors report the line", () => {
  for (const [source, expected] of [
    ["export function f takes x as\n    return x", /Line 1: Expected a type/],
    ["export function f takes x as is\n    return x", /Line 1: Expected a type, not 'is'/],
    ["export function f takes x as list text\n    return x", /Line 1: Expected 'of'/],
    ["export function f takes x as map from text\n    return x", /Line 1: Expected 'to'/],
    ["export function f takes x as number giving\n    return x", /Line 1: Expected a type/],
    ["type kind is text", /Line 1: Type names start with a capital letter/],
    ["type Kind is\n", /Line 1: Expected a type/],
    ["type Thing is object\n    name is \"x\"", /Line 2: Object types contain only fields/],
    ["if true\n    type Kind is text", /Line 2: Types must be declared at the top level/],
    ["items is object\nitems:name as text is 1", /Line 2: Expected 'is'/]
  ]) assert.throws(() => compile(source), expected, source);
  assert.equal(compile("export x as number is").declarations.split("\n")[1], "export let x: number;");
});

test("the types command writes declarations, skips current files, and checks for stale ones", () => {
  const folder = mkdtempSync(join(tmpdir(), "prose-types-"));
  const cli = fileURLToPath(new URL("../bin/prose.js", import.meta.url));
  const types = (...args) => spawnSync(process.execPath, [cli, "types", ...args], { encoding: "utf8", cwd: folder });
  try {
    writeFileSync(join(folder, "text.prose"), "export function shout takes word as text, giving text\n    return word:toUpperCase run");
    writeFileSync(join(folder, "main.prose"), 'use shout from "./text.prose"\nprint shout "hi"');
    assert.equal(types("--check", ".").status, 1);
    const written = types(".");
    assert.equal(written.status, 0, written.stderr);
    assert.match(written.stdout, /Wrote text\.d\.prose\.ts/);
    assert.equal(readFileSync(join(folder, "text.d.prose.ts"), "utf8"),
      `${header}\nexport function shout(word: string): string;\n`);
    assert.equal(types(".").stdout, "");
    writeFileSync(join(folder, "text.d.prose.ts"), readFileSync(join(folder, "text.d.prose.ts"), "utf8").replace(/\n/g, "\r\n"));
    assert.equal(types("--check", ".").status, 0);
    writeFileSync(join(folder, "text.prose"), "export function shout takes word as text, giving number\n    return 1");
    const stale = types("--check", ".");
    assert.equal(stale.status, 1);
    assert.match(stale.stderr, /Out of date.*\n  text\.d\.prose\.ts/);
    writeFileSync(join(folder, "broken.prose"), "export function f takes x as\n    return x");
    assert.match(types(".").stderr, /broken\.prose: Line 1: Expected a type/);
  } finally {
    rmSync(folder, { recursive: true, force: true });
  }
});

test("the Vite plugin writes declarations as it compiles when asked", () => {
  const folder = mkdtempSync(join(tmpdir(), "prose-vite-types-"));
  try {
    const file = join(folder, "text.prose");
    const source = "export function shout takes word as text, giving text\n    return word";
    const context = { addWatchFile() {}, error(details) { throw new Error(details.message); } };
    prose().transform.call(context, source, file);
    assert.throws(() => readFileSync(join(folder, "text.d.prose.ts")));
    prose({ declarations: true }).transform.call(context, source, file);
    assert.match(readFileSync(join(folder, "text.d.prose.ts"), "utf8"), /export function shout\(word: string\): string;/);
  } finally {
    rmSync(folder, { recursive: true, force: true });
  }
});
