import test from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { spawnSync } from "node:child_process";
import { runInNewContext } from "node:vm";
import { fileURLToPath } from "node:url";
import { compile, transpile } from "../src/transpile.js";
import prose from "../src/vite.js";

const header = "// Generated by Prose from the .prose file of the same name. Edit that file instead.";
const declarations = source => compile(source).declarations;

function run(source) {
  const output = [];
  runInNewContext(transpile(source), { console: { log: value => output.push(value) } }, { timeout: 1000 });
  return structuredClone(output);
}

test("annotated functions declare their parameter and result types, with docs from comments", () => {
  assert.equal(declarations([
    '"Small helpers."',
    "",
    '"1 entry, 3 entries."',
    "export function pluralize takes count as number, singular as text, plural as maybe text, giving text",
    '    return singular',
    "export function words takes items as list of text giving text",
    '    return ""',
    "export function nothing_back giving nothing",
    "    return"
  ].join("\n")), [
    header,
    "/** 1 entry, 3 entries. */",
    "export function pluralize(count: number, singular: string, plural?: string): string;",
    "export function words(items: string[]): string;",
    "export function nothing_back(): void;",
    ""
  ].join("\n"));
});

test("only a comment on the line just above a declaration documents it", () => {
  assert.deepEqual(declarations([
    '"--- A section heading, separated by a blank line."', "",
    "export function first giving number", "    return 1",
    '"Documents second."', "export function second giving number", "    return 2"
  ].join("\n")).split("\n").slice(1, -1), [
    "export function first(): number;", "/** Documents second. */", "export function second(): number;"
  ]);
});

test("lowercase type names become generic type variables", () => {
  assert.equal(declarations([
    "export function groupBy takes items as Iterable of item, keyOf as function taking item giving key, giving map from key to list of item",
    "    return new Map",
    "export function pair takes left as item, right as other giving Record from text to item or other",
    "    return unset"
  ].join("\n")).split("\n").slice(1, 3).join("\n"), [
    "export function groupBy<item, key>(items: Iterable<item>, keyOf: (arg1: item) => key): Map<key, item[]>;",
    "export function pair<item, other>(left: item, right: other): Record<string, item> | other;"
  ].join("\n"));
});

test("unions, literals, maybe, sets, functions, and grouping translate to TypeScript", () => {
  const lines = declarations([
    "export kind as \"day\" or \"week\" or 7 is \"day\"",
    "export tags as set of text or null is null",
    "export pick as maybe function taking text and number giving boolean is unset",
    "export rows as list of (number or unset) is array",
    "export handlers as list of function giving nothing is array",
    "export flags as list of boolean or true is array",
    "export anything as any is 1",
    "export untyped is (1, 2)",
    "export count is 3",
    "export label is \"x\"",
    "export ready is false",
    "export missing is null"
  ].join("\n")).split("\n").slice(1, -1);
  assert.deepEqual(lines, [
    'export let kind: "day" | "week" | 7;',
    "export let tags: Set<string> | null;",
    "export let pick: ((arg1: string, arg2: number) => boolean) | undefined;",
    "export let rows: (number | undefined)[];",
    "export let handlers: (() => void)[];",
    "export let flags: boolean[] | true;",
    "export let anything: any;",
    "export let untyped: any;",
    "export let count: number;",
    "export let label: string;",
    "export let ready: boolean;",
    "export let missing: null;"
  ]);
});

test("untyped and maybe trailing parameters are optional; earlier maybe parameters are not", () => {
  assert.deepEqual(declarations([
    "export function loose takes a, b", "    return a",
    "export function mixed takes a as maybe text, b as number, c", "    return a",
    "export function reserved_names takes class, default", "    return 1"
  ].join("\n")).split("\n").slice(1, -1), [
    "export function loose(a?: any, b?: any): any;",
    "export function mixed(a: string | undefined, b: number, c?: any): any;",
    "export function reserved_names(class_?: any, default_?: any): any;"
  ]);
});

